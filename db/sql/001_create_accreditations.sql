-- CIPSE XV: tabla de solicitudes de acreditación
-- Ejecutar como usuario de la aplicación con permisos CREATE TABLE / SEQUENCE no requeridos (IDENTITY).

CREATE TABLE accreditations (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(120) NOT NULL,
  lastname    VARCHAR2(120) NOT NULL,
  country     VARCHAR2(100) NOT NULL,
  email       VARCHAR2(254) NOT NULL,
  status      VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_accreditations_email UNIQUE (email),
  CONSTRAINT ck_accreditations_status
    CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX ix_accreditations_created_at ON accreditations (created_at);
